from django.db import models

from common.models import BaseModel


class FactualClaim(BaseModel):
    """
    Represents a factual claim extracted from a post or comment.
    Either post_id OR comment_id must be set, but not both.
    """
    post_id = models.ForeignKey(
        'posts.Post',
        on_delete=models.CASCADE,
        null=True,
        blank=True,
        related_name='factual_claims'
    )
    comment_id = models.ForeignKey(
        'comments.Comment',
        on_delete=models.CASCADE,
        null=True,
        blank=True,
        related_name='factual_claims'
    )
    content_fragment = models.TextField(help_text="The exact claim text extracted")
    content_position = models.JSONField(help_text="Position markers in the original text")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = 'factual_claims'
        indexes = [
            models.Index(fields=['post_id', 'content_position']),
            models.Index(fields=['comment_id', 'content_position']),
        ]
        verbose_name = 'Factual Claim'
        verbose_name_plural = 'Factual Claims'

    def __str__(self):
        source = f"Post #{self.post_id_id}" if self.post_id else f"Comment #{self.comment_id_id}"
        return f"Claim from {source}: {self.content_fragment[:30]}..."


class FactCheck(BaseModel):
    """
    Represents the fact-checking result for a factual claim.
    """
    claim = models.ForeignKey(
        FactualClaim,
        on_delete=models.CASCADE,
        related_name='fact_checks'
    )
    verdict = models.CharField(
        max_length=20,
        choices=[
            ('supported', 'Supported'),
            ('contradicted', 'Contradicted'),
            ('unrelated', 'Unrelated'),
        ]
    )
    summary = models.TextField(blank=True, null=True, help_text="Summary generated by LLM based on sources")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = 'fact_checks'
        verbose_name = 'Fact Check'
        verbose_name_plural = 'Fact Checks'

    def __str__(self):
        return f"Fact check for claim #{self.claim_id}: {self.verdict}"


class FactCheckSource(BaseModel):
    """
    Represents a source used for fact checking a claim.
    """
    fact_check = models.ForeignKey(
        FactCheck,
        on_delete=models.CASCADE,
        related_name='sources'
    )
    url = models.URLField()
    title = models.CharField(max_length=255, blank=True, null=True)
    description = models.TextField(blank=True, null=True)
    relevance_score = models.FloatField(blank=True, null=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = 'fact_check_sources'
        verbose_name = 'Fact Check Source'
        verbose_name_plural = 'Fact Check Sources'

    def __str__(self):
        return f"Source for fact check #{self.fact_check_id}: {self.title or self.url[:30]}"