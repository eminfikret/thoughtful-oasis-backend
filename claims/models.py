from django.db import models

from common.models import BaseModel


class Claim(BaseModel):
    """
    Represents a claim for fact-checking.
    Can be standalone or linked to a post or comment.
    """
    # Using IntegerField instead of ForeignKey since posts/comments don't exist yet
    post_id = models.IntegerField(null=True, blank=True, 
                                 help_text="ID of the post containing this claim, if applicable")
    comment_id = models.IntegerField(null=True, blank=True, 
                                help_text="ID of the comment containing this claim, if applicable")
    content_fragment = models.TextField(help_text="The exact claim text to be fact-checked")
    content_position = models.JSONField(null=True, blank=True, 
                                       help_text="Position markers in the original text")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = 'claims'
        indexes = [
            models.Index(fields=['post_id']),
            models.Index(fields=['comment_id']),
        ]
        verbose_name = 'Claim'
        verbose_name_plural = 'Claims'

    def __str__(self):
        if self.post_id:
            source = f"Post #{self.post_id}"
        elif self.comment_id:
            source = f"Comment #{self.comment_id}"
        else:
            source = "Standalone claim"
        return f"{source}: {self.content_fragment[:30]}..."


class FactCheck(BaseModel):
    """
    Represents the fact-checking result for a claim.
    """
    claim = models.ForeignKey(
        Claim,
        on_delete=models.CASCADE,
        related_name='fact_checks'
    )
    verdict = models.CharField(
        max_length=20,
        choices=[
            ('supported', 'Supported'),
            ('contradicted', 'Contradicted'),
            ('unrelated', 'Unrelated'),
        ]
    )
    summary = models.TextField(blank=True, null=True, 
                               help_text="Summary generated by LLM based on sources")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = 'fact_checks'
        verbose_name = 'Fact Check'
        verbose_name_plural = 'Fact Checks'

    def __str__(self):
        return f"Fact check for claim #{self.claim_id}: {self.verdict}"


class FactCheckSource(BaseModel):
    """
    Represents a source used for fact checking a claim.
    """
    fact_check = models.ForeignKey(
        FactCheck,
        on_delete=models.CASCADE,
        related_name='sources'
    )
    url = models.URLField()
    title = models.CharField(max_length=255, blank=True, null=True)
    description = models.TextField(blank=True, null=True)
    relevance_score = models.FloatField(blank=True, null=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = 'fact_check_sources'
        verbose_name = 'Fact Check Source'
        verbose_name_plural = 'Fact Check Sources'

    def __str__(self):
        return f"Source for fact check #{self.fact_check_id}: {self.title or self.url[:30]}"